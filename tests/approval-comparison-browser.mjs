import assert from 'node:assert/strict';
import http from 'node:http';
import { chromium } from 'playwright';
import { app } from '../server.js';
import { approvalExamples, MAX_UINT256 } from '../public/approval.js';
const server = http.createServer(app);
if (!process.env.CONSENT_GAP_BASE_URL) await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const base = process.env.CONSENT_GAP_BASE_URL || `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({headless:true});
try {
  for (const width of [1280, 390]) {
    const context = await browser.newContext({viewport:{width,height:900}});
    await context.addInitScript(() => {
      globalThis.copiedSummary = '';
      Object.defineProperty(navigator.clipboard, 'writeText', {configurable:true, value:async text => {globalThis.copiedSummary = text;}});
    });
    const page = await context.newPage();
    const requests = [], errors = [];
    page.on('request', request => requests.push({url:request.url(),method:request.method()}));
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base + '/inspect.html', {waitUntil:'networkidle'});
    const initialRequests = requests.length;
    const decode = async () => { await page.getByRole('button', {name:'Decode locally',exact:true}).click(); };
    const comparison = page.locator('#amount-comparison');
    const label = page.locator('#comparison-label');
    const detail = page.locator('#comparison-detail');
    await page.getByRole('button', {name:'Example: 20 tokens',exact:true}).click();
    assert.equal(await page.locator('#claimed-amount').inputValue(), '20');
    await decode();
    assert.equal(await comparison.isVisible(), true);
    assert.equal(await label.innerText(), 'Matches the amount you entered');
    assert.match(await detail.innerText(), /Exact difference: 0 tokens/);
    assert.match(await comparison.innerText(), /Matching amounts do not prove honest button text/);
    await page.getByRole('button', {name:'Copy decoded summary',exact:true}).click();
    const copied = await page.evaluate(() => globalThis.copiedSummary);
    assert.match(copied, /Button amount entered by visitor \(not verified\): 20 tokens/);
    assert.match(copied, /Comparison is numerical only/);
    assert.match(copied, /ERC-721 uses the same selector/);
    assert.doesNotMatch(copied, /calldata=|\?data=/);
    await page.locator('#claimed-amount').fill('19.999999999999999999');
    assert.equal(await page.locator('#approval-result').isVisible(), false);
    assert.equal(await detail.innerText(), '');
    assert.equal(await page.locator('#copy-status').innerText(), '');
    await decode();
    assert.match(await label.innerText(), /Request is larger/);
    assert.match(await detail.innerText(), /Exact difference: 0\.000000000000000001 tokens/);
    await page.locator('#claimed-amount').fill('21');
    await decode();
    assert.match(await label.innerText(), /Request is smaller/);
    assert.match(await detail.innerText(), /Exact difference: 1 tokens/);
    await page.locator('#decimals').fill('');
    await decode();
    assert.equal(await page.evaluate(() => document.activeElement.id), 'decimals');
    assert.match(await page.locator('#decode-error').innerText(), /Supply token decimals/);
    await page.locator('#claimed-amount').fill('');
    await decode();
    assert.equal(await comparison.isVisible(), false);
    assert.match(await page.locator('#approval-details').innerText(), /Unknown\. No token metadata lookup/);
    await page.locator('#decimals').fill('18');
    for (const amount of ['-1','1e1','1,000','<script>alert(1)</script>','0.0000000000000000001',MAX_UINT256]) {
      await page.locator('#claimed-amount').fill(amount);
      await decode();
      assert.equal(await page.locator('#approval-result').isVisible(), false);
      assert.equal(await page.evaluate(() => document.activeElement.id), 'claimed-amount');
      assert.equal(await page.locator('#claimed-amount').getAttribute('aria-invalid'), 'true');
    }
    await page.locator('#claimed-amount').fill('20');
    await page.locator('#claimed-amount').press('Enter');
    assert.equal(await page.locator('#claimed-amount').getAttribute('aria-invalid'), null);
    assert.equal(await label.innerText(), 'Matches the amount you entered');
    await page.getByRole('button', {name:'Example: zero allowance',exact:true}).click();
    assert.equal(await page.locator('#claimed-amount').inputValue(), '0');
    await decode();
    assert.match(await label.innerText(), /Matches the amount/);
    await page.getByRole('button', {name:'Example: max allowance',exact:true}).click();
    assert.equal(await page.locator('#claimed-amount').inputValue(), '20');
    await decode();
    assert.match(await label.innerText(), /Request is larger/);
    assert.match(await page.locator('#allowance-label').innerText(), /Maximum uint256/);
    await page.getByRole('button', {name:'Copy decoded summary',exact:true}).click();
    assert.match(await page.evaluate(() => globalThis.copiedSummary), /Request is larger than your entered amount/);
    const columns = await page.locator('.inspect-grid').evaluate(el => getComputedStyle(el).gridTemplateColumns.split(' ').length);
    assert.equal(columns, width > 760 ? 2 : 1);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    const screenshot = process.env.CAPTURE_AMOUNT_DEMO === '1' ? `public/demo/inspect-${width}.png` : `/tmp/consent-gap-amount-${width}.png`;
    await page.screenshot({path:screenshot,fullPage:true}); // Owned invented maximum-vs-20 data only.
    await page.getByRole('button', {name:'Clear form',exact:true}).click();
    assert.equal(await page.locator('#claimed-amount').inputValue(), '');
    assert.equal(await detail.innerText(), '');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'calldata');
    assert.equal(requests.length, initialRequests, 'comparisons, copying and reset make no network requests');
    assert.equal(new URL(page.url()).search, '');
    assert.deepEqual(await page.evaluate(async () => ({local:localStorage.length,session:sessionStorage.length,cookies:document.cookie,databases:(await indexedDB.databases()).length})), {local:0,session:0,cookies:'',databases:0});
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({width,columns,initialRequests,interactionRequests:requests.length-initialRequests,errors,screenshot,checks:'equal/larger/smaller, exact tiny gap, unknown decimals, precision/overflow refusal, keyboard recovery, copy caveats, maximum/zero, edit/reset clearing, privacy, no overflow'}));
    await context.close();
  }
  const context = await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:850}});
  const page = await context.newPage();
  const requests = [];
  page.on('request', request => requests.push(request.url()));
  await page.goto(base + '/inspect.html', {waitUntil:'networkidle'});
  const before = requests.length;
  await page.locator('#calldata').fill(approvalExamples.bounded);
  await page.locator('#decimals').fill('18');
  await page.locator('#claimed-amount').fill('20');
  await page.getByRole('button', {name:'Decode locally',exact:true}).click({noWaitAfter:true});
  assert.equal(requests.length, before, 'JS-disabled amount form cannot submit or upload');
  assert.equal(new URL(page.url()).search, '');
  console.log('JS-disabled comparison fields make no request or serialized URL');
  await context.close();
} finally {
  await browser.close();
  if (server.listening) await new Promise(resolve => server.close(resolve));
}
